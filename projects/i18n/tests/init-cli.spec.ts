import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { afterEach, describe, expect, it } from 'vitest';

/**
 * `import.meta.url` is not a `file:` URL under the Angular unit-test builder,
 * so the CLI is resolved from the workspace root, where `ng test` runs.
 */
const CLI = resolve(process.cwd(), 'projects/i18n/cli/rivinia-i18n-keys.mjs');
if (!existsSync(CLI)) {
  throw new Error(`rivinia-i18n-keys not found at ${CLI} (run the suite from the workspace root)`);
}

const dirs: string[] = [];

function tempDir(): string {
  const dir = mkdtempSync(join(tmpdir(), 'rivinia-i18n-init-'));
  dirs.push(dir);
  return dir;
}

function run(
  cwd: string,
  args: string[],
  input = '',
): { code: number; stdout: string; stderr: string } {
  const result = spawnSync(process.execPath, [CLI, ...args], { cwd, encoding: 'utf8', input });
  return { code: result.status ?? -1, stdout: result.stdout ?? '', stderr: result.stderr ?? '' };
}

const MODULE = 'src/app/i18n/languages.ts';

function modulePath(dir: string): string {
  return join(dir, MODULE);
}

function readModule(dir: string): string {
  return readFileSync(modulePath(dir), 'utf8');
}

function generated(options: {
  defaultLanguage: string;
  languages: readonly { id: string; nativeName: string; dir: string }[];
}): string {
  const entries = options.languages
    .map(
      (entry) =>
        `    { id: '${entry.id}', nativeName: '${entry.nativeName}', dir: '${entry.dir}' },`,
    )
    .join('\n');
  return [
    '// Generated by `npx rivinia-i18n-keys init`. Re-run the command to regenerate.',
    "import { defineRiviniaI18n } from '@rivinia/i18n';",
    '',
    'export const i18n = defineRiviniaI18n({',
    `  defaultLanguage: '${options.defaultLanguage}',`,
    '  languages: [',
    entries,
    '  ],',
    '});',
    '',
    '/** The typed language manager — call inside an injection context. */',
    'export const injectI18n = i18n.inject;',
    '',
  ].join('\n');
}

const AR = { id: 'ar', nativeName: 'العربية', dir: 'rtl' };
const EN = { id: 'en', nativeName: 'English', dir: 'ltr' };

afterEach(() => {
  while (dirs.length > 0) {
    rmSync(dirs.pop()!, { recursive: true, force: true });
  }
});

describe('rivinia-i18n-keys init — non-interactive', () => {
  it('writes the typed module and one dictionary per language', () => {
    const dir = tempDir();
    const { code, stdout } = run(dir, ['init', '--languages', 'ar:العربية:rtl,en:English:ltr']);

    expect(code).toBe(0);
    expect(stdout).toContain(MODULE);
    expect(stdout).toContain("from './i18n/languages'");
    expect(readModule(dir)).toBe(generated({ defaultLanguage: 'ar', languages: [AR, EN] }));
    expect(readFileSync(join(dir, 'public/i18n/ar.json'), 'utf8')).toBe('{}\n');
    expect(readFileSync(join(dir, 'public/i18n/en.json'), 'utf8')).toBe('{}\n');
  });

  it('fills native name and direction from the id when they are omitted', () => {
    const dir = tempDir();
    const { code } = run(dir, ['init', '--languages', 'ar,en']);
    expect(code).toBe(0);
    expect(readModule(dir)).toBe(generated({ defaultLanguage: 'ar', languages: [AR, EN] }));
  });

  it('honours --default, --out and --dir', () => {
    const dir = tempDir();
    const { code } = run(dir, [
      'init',
      '--languages',
      'ar:العربية:rtl,en:English:ltr',
      '--default',
      'en',
      '--out',
      'lib/i18n.ts',
      '--dir',
      'static/i18n',
    ]);

    expect(code).toBe(0);
    const module = readFileSync(join(dir, 'lib/i18n.ts'), 'utf8');
    expect(module).toContain("  defaultLanguage: 'en',");
    expect(existsSync(join(dir, 'static/i18n/en.json'))).toBe(true);
    expect(existsSync(join(dir, 'public'))).toBe(false);
  });

  it('rejects an invalid id before writing anything', () => {
    const dir = tempDir();
    const { code, stderr } = run(dir, ['init', '--languages', 'e1,en']);
    expect(code).toBe(1);
    expect(stderr).toContain('e1');
    expect(existsSync(modulePath(dir))).toBe(false);
  });

  it('rejects a duplicate id', () => {
    const dir = tempDir();
    const { code, stderr } = run(dir, ['init', '--languages', 'ar,ar']);
    expect(code).toBe(1);
    expect(stderr).toContain('Duplicate language id "ar"');
    expect(existsSync(modulePath(dir))).toBe(false);
  });

  it('rejects an invalid direction', () => {
    const dir = tempDir();
    const { code, stderr } = run(dir, ['init', '--languages', 'ar:العربية:sideways']);
    expect(code).toBe(1);
    expect(stderr).toContain('sideways');
  });

  it('rejects a --default that is not one of the ids', () => {
    const dir = tempDir();
    const { code, stderr } = run(dir, ['init', '--languages', 'ar,en', '--default', 'fr']);
    expect(code).toBe(1);
    expect(stderr).toContain('fr');
    expect(existsSync(modulePath(dir))).toBe(false);
  });

  it('refuses to overwrite a hand-written module unless --force is given', () => {
    const dir = tempDir();
    const path = modulePath(dir);
    mkdirSync(join(dir, 'src/app/i18n'), { recursive: true });
    writeFileSync(path, '// mine\nexport const x = 1;\n', 'utf8');

    const refused = run(dir, ['init', '--languages', 'ar,en']);
    expect(refused.code).toBe(1);
    expect(refused.stderr).toContain('--force');
    expect(readFileSync(path, 'utf8')).toBe('// mine\nexport const x = 1;\n');

    const forced = run(dir, ['init', '--languages', 'ar,en', '--force']);
    expect(forced.code).toBe(0);
    expect(readFileSync(path, 'utf8')).toBe(
      generated({ defaultLanguage: 'ar', languages: [AR, EN] }),
    );
  });

  it('warns when app.config.ts still calls provideRiviniaI18n directly', () => {
    const dir = tempDir();
    mkdirSync(join(dir, 'src/app'), { recursive: true });
    writeFileSync(
      join(dir, 'src/app/app.config.ts'),
      'export const appConfig = { providers: [provideRiviniaI18n({ languages: [] })] };\n',
      'utf8',
    );

    const { code, stderr } = run(dir, ['init', '--languages', 'ar,en']);
    expect(code).toBe(0);
    expect(stderr).toContain('provideRiviniaI18n');
  });

  it('keeps an existing dictionary untouched', () => {
    const dir = tempDir();
    const dictionary = join(dir, 'public/i18n/en.json');
    mkdirSync(join(dir, 'public/i18n'), { recursive: true });
    writeFileSync(dictionary, '{"hello":"Hi"}\n', 'utf8');

    const { code, stdout } = run(dir, ['init', '--languages', 'ar,en']);
    expect(code).toBe(0);
    expect(readFileSync(dictionary, 'utf8')).toBe('{"hello":"Hi"}\n');
    expect(stdout).toContain('Kept');
  });

  it('--dry-run reports the files without writing them', () => {
    const dir = tempDir();
    const { code, stdout } = run(dir, ['init', '--languages', 'ar,en', '--dry-run']);
    expect(code).toBe(0);
    expect(stdout).toContain(MODULE);
    expect(stdout).toContain('public/i18n/en.json');
    expect(existsSync(modulePath(dir))).toBe(false);
    expect(existsSync(join(dir, 'public'))).toBe(false);
  });
});

describe('rivinia-i18n-keys init — interactive', () => {
  it('collects two languages, then the default, from stdin', () => {
    const dir = tempDir();
    const { code } = run(dir, ['init'], 'ar\n\n\ny\nen\n\n\nn\n\n');
    expect(code).toBe(0);
    expect(readModule(dir)).toBe(generated({ defaultLanguage: 'ar', languages: [AR, EN] }));
    expect(readFileSync(join(dir, 'public/i18n/ar.json'), 'utf8')).toBe('{}\n');
    expect(readFileSync(join(dir, 'public/i18n/en.json'), 'utf8')).toBe('{}\n');
  });

  it('accepts the default language by id', () => {
    const dir = tempDir();
    const { code } = run(dir, ['init'], 'ar\n\n\ny\nen\n\n\nn\nen\n');
    expect(code).toBe(0);
    expect(readModule(dir)).toBe(generated({ defaultLanguage: 'en', languages: [AR, EN] }));
  });

  it('re-asks after an invalid id instead of failing', () => {
    const dir = tempDir();
    const { code } = run(dir, ['init'], '1x\nar\n\n\nn\n');
    expect(code).toBe(0);
    expect(readModule(dir)).toBe(generated({ defaultLanguage: 'ar', languages: [AR] }));
  });

  it('fails with a clear message when stdin is empty and no --languages is given', () => {
    const dir = tempDir();
    const { code, stderr } = run(dir, ['init']);
    expect(code).toBe(1);
    expect(stderr).toContain('--languages');
    expect(existsSync(modulePath(dir))).toBe(false);
  });
});
