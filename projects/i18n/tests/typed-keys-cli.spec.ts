import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { afterEach, describe, expect, it } from 'vitest';

/**
 * `import.meta.url` is not a `file:` URL under the Angular unit-test builder
 * (the module is served by the Vite dev server), so the CLI is resolved from
 * the workspace root, where `ng test` runs.
 */
const CLI = resolve(process.cwd(), 'projects/i18n/cli/rivinia-i18n-keys.mjs');
if (!existsSync(CLI)) {
  throw new Error(`rivinia-i18n-keys not found at ${CLI} (run the suite from the workspace root)`);
}

const dirs: string[] = [];

function tempDir(): string {
  const dir = mkdtempSync(join(tmpdir(), 'rivinia-i18n-keys-'));
  dirs.push(dir);
  return dir;
}

function run(cwd: string, args: string[]): { code: number; stdout: string; stderr: string } {
  const result = spawnSync(process.execPath, [CLI, ...args], { cwd, encoding: 'utf8' });
  return { code: result.status ?? -1, stdout: result.stdout ?? '', stderr: result.stderr ?? '' };
}

function writeJson(dir: string, name: string, value: unknown): string {
  const path = join(dir, name);
  mkdirSync(join(path, '..'), { recursive: true });
  writeFileSync(path, JSON.stringify(value), 'utf8');
  return path;
}

afterEach(() => {
  while (dirs.length > 0) {
    rmSync(dirs.pop()!, { recursive: true, force: true });
  }
});

describe('rivinia-i18n-keys — generation', () => {
  it('flattens nested objects to sorted dot paths', () => {
    const dir = tempDir();
    writeJson(dir, 'en.json', {
      nav: { home: 'Home' },
      app: { title: 'Title', save: 'Save' },
    });

    const { code, stdout } = run(dir, ['--source', 'en.json', '--out', 'keys.d.ts']);
    expect(code).toBe(0);
    expect(stdout).toContain('Wrote 3 keys');

    expect(readFileSync(join(dir, 'keys.d.ts'), 'utf8')).toBe(
      [
        '// Generated by @rivinia/i18n. Do not edit.',
        "import '@rivinia/i18n';",
        '',
        "declare module '@rivinia/i18n' {",
        '  interface RiviniaI18nKeyRegistry {',
        "    readonly keys: 'app.save' | 'app.title' | 'nav.home';",
        '  }',
        '}',
        '',
      ].join('\n'),
    );
  });

  it('escapes quotes and backslashes in keys', () => {
    const dir = tempDir();
    writeJson(dir, 'en.json', { "it's": 'x', 'a\\b': 'y' });

    expect(run(dir, ['--source', 'en.json', '--out', 'keys.d.ts']).code).toBe(0);
    const text = readFileSync(join(dir, 'keys.d.ts'), 'utf8');
    expect(text).toContain("'a\\\\b'");
    expect(text).toContain("'it\\'s'");
  });

  it('skips non-string leaves and warns about each one', () => {
    const dir = tempDir();
    writeJson(dir, 'en.json', {
      keep: 'x',
      num: 5,
      flag: true,
      nil: null,
      list: ['a', 'b'],
      nested: { deeper: { ok: 'y' } },
    });

    const { code, stderr } = run(dir, ['--source', 'en.json', '--out', 'keys.d.ts']);
    expect(code).toBe(0);
    expect(readFileSync(join(dir, 'keys.d.ts'), 'utf8')).toContain(
      "readonly keys: 'keep' | 'nested.deeper.ok';",
    );
    expect(stderr).toContain('num');
    expect(stderr).toContain('flag');
    expect(stderr).toContain('nil');
    expect(stderr).toContain('list');
    expect(stderr).toContain('non-string value');
  });

  it('writes a valid file for an empty dictionary', () => {
    const dir = tempDir();
    writeJson(dir, 'en.json', {});

    expect(run(dir, ['--source', 'en.json', '--out', 'keys.d.ts']).code).toBe(0);
    const text = readFileSync(join(dir, 'keys.d.ts'), 'utf8');
    expect(text).toContain('readonly keys: never;');
    expect(text.startsWith('// Generated by @rivinia/i18n.')).toBe(true);
  });

  it('uses public/i18n/en.json and src/i18n-keys.d.ts by default', () => {
    const dir = tempDir();
    writeJson(dir, 'public/i18n/en.json', { hello: 'Hello' });

    const { code } = run(dir, []);
    expect(code).toBe(0);
    expect(readFileSync(join(dir, 'src/i18n-keys.d.ts'), 'utf8')).toContain(
      "readonly keys: 'hello';",
    );
  });

  it('keeps literal dotted keys and lets them win over a nested collision', () => {
    const dir = tempDir();
    writeJson(dir, 'en.json', {
      app: { title: 'Nested title' },
      'app.title': 'Flat title',
      deep: { x: 'D' },
    });

    const { code, stderr } = run(dir, ['--source', 'en.json', '--out', 'keys.d.ts']);
    expect(code).toBe(0);
    expect(readFileSync(join(dir, 'keys.d.ts'), 'utf8')).toContain(
      "readonly keys: 'app.title' | 'deep.x';",
    );
    expect(stderr).toContain('collision');
    expect(stderr).toContain('flat key wins');
  });
});

describe('rivinia-i18n-keys — --check', () => {
  it('exits 0 when the file is up to date', () => {
    const dir = tempDir();
    writeJson(dir, 'en.json', { a: 'A' });
    expect(run(dir, ['--source', 'en.json', '--out', 'keys.d.ts']).code).toBe(0);

    const check = run(dir, ['--source', 'en.json', '--out', 'keys.d.ts', '--check']);
    expect(check.code).toBe(0);
    expect(check.stdout).toContain('up to date');
  });

  it('exits 1 and explains when the file is stale', () => {
    const dir = tempDir();
    writeJson(dir, 'en.json', { a: 'A' });
    expect(run(dir, ['--source', 'en.json', '--out', 'keys.d.ts']).code).toBe(0);

    writeJson(dir, 'en.json', { a: 'A', b: 'B' });
    const check = run(dir, ['--source', 'en.json', '--out', 'keys.d.ts', '--check']);
    expect(check.code).toBe(1);
    expect(check.stderr).toContain('stale');
    expect(check.stderr).toContain('rivinia-i18n-keys');
  });

  it('exits 1 when the output file does not exist', () => {
    const dir = tempDir();
    writeJson(dir, 'en.json', { a: 'A' });
    expect(run(dir, ['--source', 'en.json', '--out', 'keys.d.ts', '--check']).code).toBe(1);
  });
});

describe('rivinia-i18n-keys — --parity', () => {
  it('reports a missing key, an extra key and a placeholder mismatch, then exits 1', () => {
    const dir = tempDir();
    writeJson(dir, 'dict/en.json', {
      greeting: 'Hello {name}',
      bye: 'Bye',
    });
    writeJson(dir, 'dict/ar.json', {
      greeting: 'مرحبا {ism}',
      extra: 'زائد',
    });

    const { code, stderr } = run(dir, ['--parity', '--dir', 'dict', '--base', 'en']);
    expect(code).toBe(1);
    expect(stderr).toContain('MISSING ar key "bye"');
    expect(stderr).toContain('EXTRA ar key "extra"');
    expect(stderr).toContain('PLACEHOLDER ar key "greeting"');
    expect(stderr).toContain('{name}');
    expect(stderr).toContain('3 parity problem(s)');

    const lines = stderr.split('\n').filter((line) => line.includes('[rivinia/i18n] '));
    expect(lines).toHaveLength(4); // three problems + the summary
    expect(lines[0]).toContain('MISSING');
    expect(lines[1]).toContain('PLACEHOLDER');
    expect(lines[2]).toContain('EXTRA');
  });

  it('exits 0 for a clean set, across nested and flat shapes', () => {
    const dir = tempDir();
    writeJson(dir, 'dict/en.json', {
      nav: { home: 'Home', about: 'About {company}' },
      count: '{n, plural, one {# item} other {# items}}',
    });
    writeJson(dir, 'dict/ar.json', {
      'nav.home': 'الرئيسية',
      'nav.about': 'حول {company}',
      count: '{n, plural, one {عنصر} other {عناصر}}',
    });

    const { code, stdout } = run(dir, ['--parity', '--dir', 'dict', '--base', 'en']);
    expect(code).toBe(0);
    expect(stdout).toContain('Parity OK (2 dictionaries, 3 keys in "en")');
  });

  it('honours a custom base language', () => {
    const dir = tempDir();
    writeJson(dir, 'dict/fr.json', { hello: 'Bonjour' });
    writeJson(dir, 'dict/en.json', { hello: 'Hello', extra: 'Extra' });

    const { code, stderr } = run(dir, ['--parity', '--dir', 'dict', '--base', 'fr']);
    expect(code).toBe(1);
    expect(stderr).toContain('EXTRA en key "extra" (absent in "fr")');
  });

  it('exits 1 when the base dictionary is missing', () => {
    const dir = tempDir();
    writeJson(dir, 'dict/en.json', { a: 'A' });
    const { code, stderr } = run(dir, ['--parity', '--dir', 'dict', '--base', 'de']);
    expect(code).toBe(1);
    expect(stderr).toContain('Base dictionary "de.json" not found');
  });

  it('ignores quoted braces when comparing placeholders', () => {
    const dir = tempDir();
    writeJson(dir, 'dict/en.json', { literal: "It''s '{'not a param'}'" });
    writeJson(dir, 'dict/ar.json', { literal: "إنه '{'ليس معاملاً'}'" });

    expect(run(dir, ['--parity', '--dir', 'dict', '--base', 'en']).code).toBe(0);
  });

  it('does not read plural branch text as a parameter', () => {
    const dir = tempDir();
    writeJson(dir, 'dict/en.json', {
      items: '{count, plural, =0 {No items} one {# item} other {# items}}',
      guests: '{n, plural, offset:1 =0 {Nobody} =1 {Only you} other {You and # others}}',
    });
    writeJson(dir, 'dict/ar.json', {
      items: '{count, plural, zero {لا عناصر} one {عنصر} other {عناصر}}',
      guests: '{n, plural, offset:1 =0 {لا أحد} =1 {أنت فقط} other {أنت و# آخرين}}',
    });

    const { code, stdout } = run(dir, ['--parity', '--dir', 'dict', '--base', 'en']);
    expect(code).toBe(0);
    expect(stdout).toContain('Parity OK (2 dictionaries, 2 keys in "en")');
  });

  it('compares placeholders nested inside plural and select branches', () => {
    const dir = tempDir();
    writeJson(dir, 'dict/en.json', {
      items: '{count, plural, one {{name} bought one} other {{name} bought #}}',
      them: '{who, select, other {{topic} for {name}}}',
    });
    writeJson(dir, 'dict/ar.json', {
      items: '{count, plural, one {{name} اشترى واحدًا} other {{name} اشترى #}}',
      them: '{who, select, other {{topic} لـ {ism}}}',
    });

    const { code, stderr } = run(dir, ['--parity', '--dir', 'dict', '--base', 'en']);
    expect(code).toBe(1);
    expect(stderr).toContain('PLACEHOLDER ar key "them"');
    expect(stderr).toContain('{name}');
    expect(stderr).toContain('1 parity problem(s)');
  });
});

describe('rivinia-i18n-keys — failures', () => {
  it('exits 1 with a message when the source is missing', () => {
    const dir = tempDir();
    const result = run(dir, ['--source', 'nope.json', '--out', 'keys.d.ts']);
    expect(result.code).toBe(1);
    expect(result.stderr).toContain('Source dictionary not found');
  });

  it('exits 1 when the source is not valid JSON', () => {
    const dir = tempDir();
    writeFileSync(join(dir, 'bad.json'), '{ nope', 'utf8');
    const result = run(dir, ['--source', 'bad.json', '--out', 'keys.d.ts']);
    expect(result.code).toBe(1);
    expect(result.stderr).toContain('Could not parse');
  });

  it('exits 1 on an unknown option', () => {
    const dir = tempDir();
    const result = run(dir, ['--wat']);
    expect(result.code).toBe(1);
    expect(result.stderr).toContain('Unknown option');
  });

  it('exits 1 when a flag has no value', () => {
    const dir = tempDir();
    const result = run(dir, ['--source']);
    expect(result.code).toBe(1);
    expect(result.stderr).toContain('needs a path');
  });
});
