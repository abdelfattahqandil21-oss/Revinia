import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { afterAll, describe, expect, it } from 'vitest';

/**
 * Type-level proof for the typed-key registry, run as a real `tsc` compilation
 * (a `.d.ts` seam cannot be proven by a runtime assertion — `@ts-expect-error`
 * only means something to the compiler).
 *
 * The fixture imports the package's SOURCE entry point, so this suite does not
 * depend on `dist/` being built first. The published `.d.ts` is verified
 * separately by the tarball gate.
 */

const ROOT = process.cwd();
const FIXTURE = resolve(ROOT, 'tmp/typed-keys-fixture');
const TSC = resolve(ROOT, 'node_modules/typescript/bin/tsc');
const PUBLIC_API = resolve(ROOT, 'projects/i18n/src/public-api.ts');

/** Relative to `<repo>/tmp/typed-keys-fixture/<program>/tsconfig.json`. */
const PACKAGE_PATH = '../../../projects/i18n/src/public-api.ts';

if (!existsSync(TSC)) throw new Error(`typescript not found at ${TSC}`);
if (!existsSync(PUBLIC_API)) throw new Error(`i18n source not found at ${PUBLIC_API}`);

function programTsconfig(): string {
  return JSON.stringify(
    {
      compilerOptions: {
        strict: true,
        noEmit: true,
        skipLibCheck: true,
        target: 'ES2022',
        module: 'ES2022',
        moduleResolution: 'bundler',
        experimentalDecorators: true,
        types: [],
        // TS6 deprecates `baseUrl`; without it, `paths` values resolve
        // relative to this tsconfig.
        paths: { '@rivinia/i18n': [PACKAGE_PATH] },
      },
      include: ['*.ts'],
    },
    null,
    2,
  );
}

/** The file the CLI generates, kept verbatim in shape. */
const KEYS_DTS = [
  '// Generated by @rivinia/i18n. Do not edit.',
  "import '@rivinia/i18n';",
  '',
  "declare module '@rivinia/i18n' {",
  '  interface RiviniaI18nKeyRegistry {',
  "    readonly keys: 'app.title' | 'app.save';",
  '  }',
  '}',
  '',
].join('\n');

/** Valid calls, plus a typo the compiler MUST reject. */
const TYPED_USAGE = [
  "import type { RegisteredI18nKey, RiviniaI18n } from '@rivinia/i18n';",
  '',
  "declare const i18n: RiviniaI18n<'ar' | 'en'>;",
  '',
  "i18n.translate('app.title');",
  "i18n.translate('app.title', { name: 'A' });",
  "i18n.translate('app.save', 'Fallback');",
  "i18n.t('app.title');",
  "i18n.t('app.save', { name: 'A' });",
  '',
  '// A dynamic key is asserted explicitly — the documented escape hatch.',
  'const dynamic = `status.${String(1)}` as RegisteredI18nKey;',
  'i18n.translate(dynamic);',
  '',
  '// @ts-expect-error — the key is not in the generated registry.',
  "i18n.translate('app.titel');",
  '// @ts-expect-error — same typo through the signal API.',
  "i18n.t('app.titel');",
  '',
].join('\n');

/** The same typo, with no `@ts-expect-error`: tsc must fail and say why. */
const BAD_USAGE = [
  "import type { RiviniaI18n } from '@rivinia/i18n';",
  '',
  "declare const i18n: RiviniaI18n<'ar' | 'en'>;",
  '',
  "i18n.translate('app.titel');",
  '',
].join('\n');

/** An app that never augments the registry: every string key stays legal. */
const UNTYPED_USAGE = [
  "import type { RiviniaI18n } from '@rivinia/i18n';",
  '',
  "declare const i18n: RiviniaI18n<'ar' | 'en'>;",
  '',
  "i18n.translate('app.titel');",
  "i18n.translate('anything.at.all');",
  "i18n.t('not.generated.either');",
  '',
].join('\n');

function writeProgram(name: string, files: Record<string, string>): string {
  const dir = join(FIXTURE, name);
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, 'tsconfig.json'), programTsconfig(), 'utf8');
  for (const [file, content] of Object.entries(files)) {
    writeFileSync(join(dir, file), content, 'utf8');
  }
  return dir;
}

function compile(
  name: string,
  files: Record<string, string>,
): { code: number; output: string } {
  const dir = writeProgram(name, files);
  const result = spawnSync(process.execPath, [TSC, '--noEmit', '-p', join(dir, 'tsconfig.json')], {
    cwd: ROOT,
    encoding: 'utf8',
  });
  // `tsc` prints diagnostics on stdout; anything on stderr is an environment
  // failure, so both are inspected rather than one being assumed empty.
  return {
    code: result.status ?? -1,
    output: `${result.stdout ?? ''}${result.stderr ?? ''}`,
  };
}

afterAll(() => {
  rmSync(FIXTURE, { recursive: true, force: true });
});

describe('typed keys — the registry is a real compile-time contract', () => {
  it('compiles a generated registry with valid keys and the dynamic escape hatch', () => {
    const result = compile('typed', { 'keys.d.ts': KEYS_DTS, 'usage.ts': TYPED_USAGE });
    // A silent `@ts-expect-error` would fail here ("Unused '@ts-expect-error'
    // directive"), which is exactly the negative control this test needs.
    expect(result.output).not.toContain('Unused');
    expect(result.code, result.output).toBe(0);
  });

  it('rejects a key that is not in the registry, naming the key and the allowed set', () => {
    const result = compile('bad', { 'keys.d.ts': KEYS_DTS, 'usage.ts': BAD_USAGE });
    // `tsc` exits 2 (diagnostics with --noEmit); a config problem would be 3.
    expect(result.code, result.output).toBe(2);
    expect(result.output).toContain('app.titel');
    // The registry resolves to its literal union in the message, so the
    // consumer sees the legal keys, not an opaque alias name.
    expect(result.output).toContain('"app.title" | "app.save"');
    expect(result.output).toContain('usage.ts');
  });

  it('accepts any key when the registry is not augmented', () => {
    const result = compile('untyped', { 'usage.ts': UNTYPED_USAGE });
    expect(result.output).toBe('');
    expect(result.code).toBe(0);
  });

  it('keeps the generated file self-describing (the CLI output shape)', () => {
    // Guards the fixture itself: if the CLI's emitted shape ever changes, this
    // suite must be updated rather than silently proving the wrong thing.
    expect(KEYS_DTS.startsWith('// Generated by @rivinia/i18n. Do not edit.')).toBe(true);
    expect(KEYS_DTS).toContain("interface RiviniaI18nKeyRegistry");
    expect(readFileSync(PUBLIC_API, 'utf8')).toContain('RiviniaI18nKeyRegistry');
  });
});
