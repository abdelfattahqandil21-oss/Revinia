#!/usr/bin/env node
/**
 * `rivinia-i18n-keys` — generates the typed-key registry for `@rivinia/i18n`
 * and checks key/placeholder parity across dictionaries.
 *
 *   npx rivinia-i18n-keys
 *   npx rivinia-i18n-keys --source public/i18n/en.json --out src/i18n-keys.d.ts
 *   npx rivinia-i18n-keys --check        # CI: exit 1 when the file is stale
 *   npx rivinia-i18n-keys --parity --dir public/i18n --base en
 *
 * Nested objects flatten to dot paths, literal dotted keys are kept as-is,
 * only string leaves become keys, keys are sorted for stable diffs, and quotes
 * are escaped. No dependencies.
 */
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, basename, join, relative, resolve } from 'node:path';

const DEFAULTS = Object.freeze({
  source: 'public/i18n/en.json',
  out: 'src/i18n-keys.d.ts',
  dir: 'public/i18n',
  base: 'en',
});

const INIT_DEFAULTS = Object.freeze({
  out: 'src/app/i18n/languages.ts',
  dir: 'public/i18n',
});

const PREFIX = '[rivinia/i18n]';

/** Generated-file marker; its absence means a hand-written file we must not clobber. */
const INIT_BANNER =
  '// Generated by `npx rivinia-i18n-keys init`. Re-run the command to regenerate.';

const LANGUAGE_ID = /^[a-z]{2,8}(-[a-z0-9]{2,8})?$/;

/** Display names and directions for the ids most projects start with. */
const KNOWN_LANGUAGES = Object.freeze({
  ar: { nativeName: 'العربية', dir: 'rtl' },
  en: { nativeName: 'English', dir: 'ltr' },
  fr: { nativeName: 'Français', dir: 'ltr' },
  de: { nativeName: 'Deutsch', dir: 'ltr' },
  es: { nativeName: 'Español', dir: 'ltr' },
  he: { nativeName: 'עברית', dir: 'rtl' },
  fa: { nativeName: 'فارسی', dir: 'rtl' },
  ur: { nativeName: 'اردو', dir: 'rtl' },
});

const RTL_IDS = new Set(['ar', 'he', 'fa', 'ur', 'ps', 'yi', 'dv', 'ku', 'sd']);

async function main(argv) {
  if (argv[0] === 'init') {
    return runInit(parseInitArgs(argv.slice(1)));
  }
  const args = parseArgs(argv);
  if (args.error) {
    console.error(`${PREFIX} ${args.error}`);
    printHelp();
    return 1;
  }
  if (args.help) {
    printHelp();
    return 0;
  }
  return args.parity ? runParity(args) : runGenerate(args);
}

function runGenerate(args) {
  const sourcePath = resolve(args.source ?? DEFAULTS.source);
  const outPath = resolve(args.out ?? DEFAULTS.out);

  const dictionary = readDictionary(sourcePath);
  if (dictionary === null) return 1;

  const entries = new Map();
  flatten(dictionary, '', entries);
  const keys = [...entries.keys()].sort();
  const output = render(keys);

  if (args.check) {
    const current = existsSync(outPath) ? readFileSync(outPath, 'utf8') : null;
    if (current === output) {
      console.log(`${PREFIX} ${outPath} is up to date (${keys.length} keys).`);
      return 0;
    }
    console.error(
      `${PREFIX} ${outPath} is stale. Regenerate it:\n` +
        `  npx rivinia-i18n-keys --source ${relative(process.cwd(), sourcePath)} ` +
        `--out ${relative(process.cwd(), outPath)}`,
    );
    return 1;
  }

  mkdirSync(dirname(outPath), { recursive: true });
  writeFileSync(outPath, output, 'utf8');
  console.log(`${PREFIX} Wrote ${keys.length} keys to ${outPath}.`);
  return 0;
}

/**
 * `--parity`: every `<lang>.json` in `--dir` must have the same keys as
 * `--base`, and every placeholder used by the base string must appear in the
 * translated string. Sorted output, exit 1 on any mismatch (CI-friendly).
 */
function runParity(args) {
  const dir = resolve(args.dir ?? DEFAULTS.dir);
  const base = args.base ?? DEFAULTS.base;

  if (!existsSync(dir)) {
    console.error(`${PREFIX} Dictionary directory not found: ${dir}`);
    return 1;
  }

  const files = readdirSync(dir)
    .filter((file) => file.endsWith('.json'))
    .sort();
  if (files.length === 0) {
    console.error(`${PREFIX} No JSON dictionaries in ${dir}`);
    return 1;
  }

  const dictionaries = new Map();
  for (const file of files) {
    const language = basename(file, '.json');
    const path = join(dir, file);
    const dictionary = readDictionary(path);
    if (dictionary === null) return 1;
    const entries = new Map();
    flatten(dictionary, '', entries);
    dictionaries.set(language, entries);
  }

  const baseEntries = dictionaries.get(base);
  if (baseEntries === undefined) {
    console.error(`${PREFIX} Base dictionary "${base}.json" not found in ${dir}`);
    return 1;
  }

  const problems = [];
  for (const language of [...dictionaries.keys()].sort()) {
    if (language === base) continue;
    const entries = dictionaries.get(language);

    for (const key of [...baseEntries.keys()].sort()) {
      if (!entries.has(key)) {
        problems.push(
          `${PREFIX} MISSING ${language} key "${key}" (present in "${base}")`,
        );
        continue;
      }
      const expected = placeholders(baseEntries.get(key).value);
      const actual = placeholders(entries.get(key).value);
      for (const name of [...expected].sort()) {
        if (!actual.has(name)) {
          problems.push(
            `${PREFIX} PLACEHOLDER ${language} key "${key}": ` +
              `{${name}} is used in "${base}" but absent from "${language}"`,
          );
        }
      }
    }

    for (const key of [...entries.keys()].sort()) {
      if (!baseEntries.has(key)) {
        problems.push(`${PREFIX} EXTRA ${language} key "${key}" (absent in "${base}")`);
      }
    }
  }

  if (problems.length === 0) {
    console.log(
      `${PREFIX} Parity OK (${dictionaries.size} dictionaries, ` +
        `${baseEntries.size} keys in "${base}").`,
    );
    return 0;
  }

  for (const line of problems) console.error(line);
  console.error(
    `${PREFIX} ${problems.length} parity problem(s) across ${dictionaries.size} dictionaries.`,
  );
  return 1;
}

/**
 * `init` — collects the languages once and writes:
 *   <out>            a `defineRiviniaI18n` module plus a typed `injectI18n`
 *   <dir>/<id>.json  one empty dictionary per language (existing files kept)
 *
 * Ids, directions and duplicates are validated before anything is written, so a
 * bad answer never leaves half a project behind.
 */
async function runInit(args) {
  if (args.error) {
    console.error(`${PREFIX} ${args.error}`);
    printInitHelp();
    return 1;
  }
  if (args.help) {
    printInitHelp();
    return 0;
  }

  let plan;
  try {
    plan = args.languages
      ? { entries: parseLanguageSpec(args.languages), defaultId: args.default ?? null }
      : await collectLanguages();
  } catch (error) {
    console.error(`${PREFIX} ${error.message}`);
    return 1;
  }
  if (plan === null) {
    console.error(
      `${PREFIX} No languages entered. Pass them non-interactively: ` +
        '`--languages ar:العربية:rtl,en:English:ltr`.',
    );
    return 1;
  }

  const { entries } = plan;
  const defaultId = plan.defaultId ?? entries[0].id;
  if (!entries.some((entry) => entry.id === defaultId)) {
    console.error(`${PREFIX} --default "${defaultId}" is not one of the language ids.`);
    return 1;
  }

  const outPath = resolve(args.out ?? INIT_DEFAULTS.out);
  const dirPath = resolve(args.dir ?? INIT_DEFAULTS.dir);

  if (existsSync(outPath) && !readFileSync(outPath, 'utf8').startsWith(INIT_BANNER)) {
    if (!args.force) {
      console.error(
        `${PREFIX} ${outPath} exists and was not generated by this command. ` +
          'Pass --force to overwrite it.',
      );
      return 1;
    }
  }

  const dictionaryPaths = entries.map((entry) => ({
    id: entry.id,
    path: join(dirPath, `${entry.id}.json`),
  }));

  if (args.dryRun) {
    console.log(`Would write ${outPath}`);
    for (const dictionary of dictionaryPaths) {
      console.log(`Would write ${dictionary.path}`);
    }
    return 0;
  }

  mkdirSync(dirname(outPath), { recursive: true });
  writeFileSync(outPath, renderLanguagesModule(entries, defaultId), 'utf8');
  console.log(`Wrote ${outPath}`);

  mkdirSync(dirPath, { recursive: true });
  for (const dictionary of dictionaryPaths) {
    if (existsSync(dictionary.path)) {
      console.log(`Kept ${dictionary.path} (already exists)`);
      continue;
    }
    writeFileSync(dictionary.path, '{}\n', 'utf8');
    console.log(`Wrote ${dictionary.path}`);
  }

  const appConfig = resolve('src/app/app.config.ts');
  if (existsSync(appConfig) && readFileSync(appConfig, 'utf8').includes('provideRiviniaI18n(')) {
    console.warn(
      `${PREFIX} app.config.ts already calls provideRiviniaI18n(…) — ` +
        'remove that call and use i18n.provide() instead, or the app registers two managers.',
    );
  }

  const relativeImport = relative(resolve('src/app'), outPath).replace(/\.ts$/, '');
  const specifier = relativeImport.startsWith('.') ? relativeImport : `./${relativeImport}`;
  console.log('');
  console.log(
    `Next: in src/app/app.config.ts add \`import { i18n } from '${specifier}';\` ` +
      'and use providers: [i18n.provide()].',
  );
  return 0;
}

/**
 * Parses `ar:العربية:rtl,en:English:ltr`. Every part after the id is optional:
 * a missing native name or direction comes from the id. `:` is the separator,
 * so a native name containing a colon must be edited in the generated file.
 */
function parseLanguageSpec(raw) {
  const entries = [];
  const seen = new Set();
  for (const part of raw.split(',')) {
    if (part.trim() === '') continue;
    const [idPart, nativePart, dirPart] = part.split(':');
    const id = idPart.trim().toLowerCase();
    if (id === '') {
      throw new Error('A language entry needs an id, e.g. `ar:العربية:rtl`.');
    }
    if (!LANGUAGE_ID.test(id)) {
      throw new Error(`Invalid language id "${id}" — use ar, en, ar-EG …`);
    }
    if (seen.has(id)) {
      throw new Error(`Duplicate language id "${id}".`);
    }
    seen.add(id);

    const known = KNOWN_LANGUAGES[id];
    const nativeName = (nativePart ?? '').trim() || known?.nativeName || id;
    const dir = (
      (dirPart ?? '').trim() ||
      known?.dir ||
      (RTL_IDS.has(id) ? 'rtl' : 'ltr')
    ).toLowerCase();
    if (dir !== 'ltr' && dir !== 'rtl') {
      throw new Error(`Invalid direction "${dir}" for "${id}" — use ltr or rtl.`);
    }
    entries.push({ id, nativeName, dir });
  }
  if (entries.length === 0) {
    throw new Error('No language ids found in --languages.');
  }
  return entries;
}

/**
 * Asks for each language, then for the default when there is more than one.
 *
 * A terminal answers through `readline.question` so editing works. A pipe
 * cannot: stdout is not a TTY and the lines arrive before the next question is
 * asked, so answers are queued from the `line` event instead. Both adapters
 * expose the same `ask` and return `null` once the input is exhausted.
 */
async function collectLanguages() {
  const prompter = await openPrompter();
  try {
    const entries = [];
    const seen = new Set();
    for (;;) {
      let id = null;
      while (id === null) {
        const raw = await prompter.ask(`${PREFIX} Language id (ar, en, ar-EG …): `);
        if (raw === null) return null;
        const candidate = raw.toLowerCase();
        if (candidate === '') {
          console.error(`${PREFIX} A language needs an id.`);
        } else if (!LANGUAGE_ID.test(candidate)) {
          console.error(`${PREFIX} Invalid language id "${candidate}" — use ar, en, ar-EG …`);
        } else if (seen.has(candidate)) {
          console.error(`${PREFIX} Duplicate language id "${candidate}".`);
        } else {
          seen.add(candidate);
          id = candidate;
        }
      }

      const known = KNOWN_LANGUAGES[id];
      const nativeDefault = known?.nativeName ?? id;
      const dirDefault = known?.dir ?? (RTL_IDS.has(id) ? 'rtl' : 'ltr');

      const nativeAnswer = await prompter.ask(`  Native name [${nativeDefault}]: `);
      if (nativeAnswer === null) return null;

      let dir = '';
      for (;;) {
        const dirAnswer = await prompter.ask(`  Direction (ltr/rtl) [${dirDefault}]: `);
        if (dirAnswer === null) return null;
        dir = (dirAnswer || dirDefault).toLowerCase();
        if (dir === 'ltr' || dir === 'rtl') break;
        console.error(`${PREFIX} Direction must be ltr or rtl.`);
      }

      entries.push({
        id,
        nativeName: nativeAnswer === '' ? nativeDefault : nativeAnswer,
        dir,
      });

      const againDefault = entries.length === 1 ? 'y' : 'n';
      const again = await prompter.ask(
        `  Another language? (${againDefault === 'y' ? 'Y/n' : 'y/N'}): `,
      );
      if (again === null) return null;
      if (!(again || againDefault).toLowerCase().startsWith('y')) break;
    }

    let defaultId = entries[0].id;
    if (entries.length > 1) {
      const choices = entries.map((entry, index) => `(${index + 1}) ${entry.id}`).join('  ');
      for (;;) {
        const raw = await prompter.ask(`${PREFIX} Default language — ${choices} [1]: `);
        if (raw === null) return null;
        if (raw === '') break;
        const index = Number(raw);
        if (Number.isInteger(index) && index >= 1 && index <= entries.length) {
          defaultId = entries[index - 1].id;
          break;
        }
        const byId = entries.find((entry) => entry.id === raw.toLowerCase());
        if (byId) {
          defaultId = byId.id;
          break;
        }
        console.error(
          `${PREFIX} Pick 1-${entries.length} or one of: ${entries.map((entry) => entry.id).join(', ')}.`,
        );
      }
    }

    return { entries, defaultId };
  } finally {
    prompter.close();
  }
}

async function openPrompter() {
  if (process.stdin.isTTY !== true) {
    const { createInterface } = await import('node:readline');
    const rl = createInterface({ input: process.stdin, terminal: false });
    const queued = [];
    const waiting = [];
    let closed = false;
    rl.on('line', (line) => {
      const next = waiting.shift();
      if (next) next(line);
      else queued.push(line);
    });
    rl.on('close', () => {
      closed = true;
      for (const next of waiting.splice(0)) next(null);
    });
    return {
      ask: async (question) => {
        process.stdout.write(question);
        if (queued.length > 0) return queued.shift().trim();
        if (closed) return null;
        const line = await new Promise((resolve) => waiting.push(resolve));
        return line === null ? null : line.trim();
      },
      close: () => rl.close(),
    };
  }

  const { createInterface } = await import('node:readline/promises');
  const rl = createInterface({ input: process.stdin, output: process.stdout });
  let closed = false;
  const onClose = new Promise((resolve) => {
    rl.once('close', () => {
      closed = true;
      resolve(null);
    });
  });
  return {
    ask: async (question) => {
      if (closed) return null;
      const answer = rl.question(question);
      answer.catch(() => {});
      const value = await Promise.race([answer, onClose]);
      return value === null ? null : value.trim();
    },
    close: () => rl.close(),
  };
}

function renderLanguagesModule(entries, defaultId) {
  const languages = entries
    .map(
      (entry) =>
        `    { id: '${escapeTs(entry.id)}', nativeName: '${escapeTs(entry.nativeName)}', dir: '${entry.dir}' },`,
    )
    .join('\n');
  return [
    INIT_BANNER,
    "import { defineRiviniaI18n } from '@rivinia/i18n';",
    '',
    'export const i18n = defineRiviniaI18n({',
    `  defaultLanguage: '${escapeTs(defaultId)}',`,
    '  languages: [',
    languages,
    '  ],',
    '});',
    '',
    '/** The typed language manager — call inside an injection context. */',
    'export const injectI18n = i18n.inject;',
    '',
  ].join('\n');
}

function escapeTs(value) {
  return String(value).replace(/\\/g, '\\\\').replace(/'/g, "\\'");
}

function parseInitArgs(argv) {
  const args = {};
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    if (arg === '--force') {
      args.force = true;
    } else if (arg === '--dry-run') {
      args.dryRun = true;
    } else if (arg === '--help' || arg === '-h') {
      args.help = true;
    } else if (arg === '--languages' || arg === '--default' || arg === '--out' || arg === '--dir') {
      const value = argv[i + 1];
      if (value === undefined || value.startsWith('--')) {
        return { error: `${arg} needs a value.` };
      }
      args[arg.slice(2)] = value;
      i++;
    } else if (
      arg.startsWith('--languages=') ||
      arg.startsWith('--default=') ||
      arg.startsWith('--out=') ||
      arg.startsWith('--dir=')
    ) {
      const eq = arg.indexOf('=');
      args[arg.slice(2, eq)] = arg.slice(eq + 1);
    } else {
      return { error: `Unknown option for init: ${arg}` };
    }
  }
  return args;
}

function printInitHelp() {
  console.log(
    [
      'rivinia-i18n-keys init — generate the language module and empty dictionaries',
      '',
      'Usage:',
      '  rivinia-i18n-keys init                      (asks for each language)',
      '  rivinia-i18n-keys init --languages <list>   (non-interactive)',
      '',
      'Options:',
      '  --languages  id[:nativeName[:dir]] pairs, comma-separated',
      '               (e.g. ar:العربية:rtl,en:English:ltr; parts after the id are optional)',
      `  --default    Default language id (default: the first one)`,
      `  --out        Module to write (default: ${INIT_DEFAULTS.out})`,
      `  --dir        Dictionary folder (default: ${INIT_DEFAULTS.dir})`,
      '  --force      Overwrite <out> even when it was written by hand',
      '  --dry-run    Print the files without writing them',
      '  --help       Show this help',
    ].join('\n'),
  );
}

function readDictionary(path) {
  if (!existsSync(path)) {
    console.error(`${PREFIX} Source dictionary not found: ${path}`);
    return null;
  }
  try {
    return JSON.parse(readFileSync(path, 'utf8'));
  } catch (error) {
    console.error(`${PREFIX} Could not parse ${path}: ${error.message}`);
    return null;
  }
}

function parseArgs(argv) {
  const args = {};
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    if (arg === '--check') {
      args.check = true;
    } else if (arg === '--parity') {
      args.parity = true;
    } else if (arg === '--help' || arg === '-h') {
      args.help = true;
    } else if (arg === '--source' || arg === '--out' || arg === '--dir' || arg === '--base') {
      const value = argv[i + 1];
      if (value === undefined || value.startsWith('--')) {
        return { error: `${arg} needs a ${arg === '--base' ? 'language' : 'path'}.` };
      }
      args[arg.slice(2)] = value;
      i++;
    } else if (
      arg.startsWith('--source=') ||
      arg.startsWith('--out=') ||
      arg.startsWith('--dir=') ||
      arg.startsWith('--base=')
    ) {
      const eq = arg.indexOf('=');
      args[arg.slice(2, eq)] = arg.slice(eq + 1);
    } else {
      return { error: `Unknown option: ${arg}` };
    }
  }
  return args;
}

/**
 * Collects string leaves in `entries` (key → { value, flat, sourcePath }).
 * A JSON key that itself contains dots (an export from many tools) is already
 * a full key; when it collides with a nested path the literal key wins and a
 * warning is printed.
 */
function flatten(value, prefix, entries) {
  if (Array.isArray(value)) {
    warn(`Skipping array at "${prefix || '(root)'}" — arrays are not keys.`);
    return;
  }
  if (value !== null && typeof value === 'object') {
    for (const [key, child] of Object.entries(value)) {
      const path = prefix ? `${prefix}.${key}` : key;
      if (child !== null && typeof child === 'object' && !Array.isArray(child)) {
        flatten(child, path, entries);
        continue;
      }
      if (typeof child === 'string') {
        addEntry(entries, path, child, key.includes('.'), path);
        continue;
      }
      if (Array.isArray(child)) {
        warn(`Skipping array at "${path}" — arrays are not keys.`);
        continue;
      }
      warn(`Skipping non-string value at "${path}" (${typeOf(child)}).`);
    }
    return;
  }
  warn(`Skipping non-string value at "${prefix || '(root)'}" (${typeOf(value)}).`);
}

function addEntry(entries, key, value, flat, sourcePath) {
  const existing = entries.get(key);
  if (existing === undefined) {
    entries.set(key, { value, flat, sourcePath });
    return;
  }
  if (existing.flat && !flat) {
    warn(`Key collision at "${key}": keeping the flat key over "${sourcePath}".`);
    return;
  }
  if (!existing.flat && flat) {
    warn(`Key collision at "${key}": the flat key wins over "${existing.sourcePath}".`);
    entries.set(key, { value, flat, sourcePath });
    return;
  }
  warn(
    `Key collision at "${key}" between "${existing.sourcePath}" and "${sourcePath}"; ` +
      'keeping the first value.',
  );
}

const NAME = /^[A-Za-z_][A-Za-z0-9_.-]*$/;
const BRANCH_TYPES = new Set(['plural', 'selectordinal', 'select']);

/**
 * Named arguments of an ICU message: every `{name …}` argument at any nesting
 * depth. Branch bodies are message text, not arguments, so their words are
 * never reported — `=0 {No items}` must not yield a `{No}` parameter.
 */
function placeholders(message) {
  const names = new Set();
  if (typeof message !== 'string') return names;
  collectPlaceholders(message, 0, message.length, names);
  return names;
}

function collectPlaceholders(text, start, end, names) {
  let i = start;
  while (i < end) {
    const char = text[i];
    if (char === "'") {
      i = skipQuote(text, i, end);
    } else if (char === '{') {
      i = readArgument(text, i, end, names);
    } else {
      i++;
    }
  }
}

/** ICU: `''` is one apostrophe; `'` before `{`, `}` or `#` quotes until `'`. */
function skipQuote(text, i, end) {
  if (text[i + 1] === "'") return i + 2;
  const next = text[i + 1];
  if (next === '{' || next === '}' || next === '#') {
    const close = text.indexOf("'", i + 2);
    return close === -1 || close >= end ? end : close + 1;
  }
  return i + 1;
}

/** Index of the `}` closing the `{` at `open`; `end` when malformed. */
function matchBrace(text, open, end) {
  let depth = 0;
  for (let i = open; i < end; i++) {
    const char = text[i];
    if (char === "'") {
      i = skipQuote(text, i, end) - 1;
    } else if (char === '{') {
      depth++;
    } else if (char === '}' && --depth === 0) {
      return i;
    }
  }
  return end;
}

function readArgument(text, open, end, names) {
  const close = matchBrace(text, open, end);
  let i = open + 1;
  while (i < close && /\s/.test(text[i])) i++;
  const nameStart = i;
  while (i < close && text[i] !== ',' && text[i] !== '}') i++;
  const name = text.slice(nameStart, i).trim();
  if (NAME.test(name)) names.add(name);
  if (i >= close || text[i] === '}') return close + 1;

  i++; // past the comma
  while (i < close && /\s/.test(text[i])) i++;
  const typeStart = i;
  while (i < close && text[i] !== ',' && text[i] !== '}') i++;
  if (BRANCH_TYPES.has(text.slice(typeStart, i).trim())) {
    collectBranches(text, i, close, names);
  }
  return close + 1;
}

/** Selector words are ignored; each `{…}` branch body is a nested message. */
function collectBranches(text, start, end, names) {
  let i = start;
  while (i < end) {
    const char = text[i];
    if (char === "'") {
      i = skipQuote(text, i, end);
    } else if (char === '{') {
      const close = matchBrace(text, i, end);
      collectPlaceholders(text, i + 1, close, names);
      i = close + 1;
    } else {
      i++;
    }
  }
}

function typeOf(value) {
  if (value === null) return 'null';
  return typeof value;
}

function warn(message) {
  console.warn(`${PREFIX} ${message}`);
}

function render(keys) {
  const union = keys.length === 0 ? 'never' : keys.map((key) => `'${escapeKey(key)}'`).join(' | ');
  return [
    '// Generated by @rivinia/i18n. Do not edit.',
    "import '@rivinia/i18n';",
    '',
    "declare module '@rivinia/i18n' {",
    '  interface RiviniaI18nKeyRegistry {',
    `    readonly keys: ${union};`,
    '  }',
    '}',
    '',
  ].join('\n');
}

function escapeKey(key) {
  return key.replace(/\\/g, '\\\\').replace(/'/g, "\\'");
}

